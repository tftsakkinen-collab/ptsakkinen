export const AMAZON_ASSOCIATE_TAG = "ptsakkinen-20";

export function getAmazonUrl(item: GearItem): string {
  if (item.amazonUrl) {
    if (item.amazonUrl.includes("tag=")) return item.amazonUrl;
    const separator = item.amazonUrl.includes("?") ? "&" : "?";
    return `${item.amazonUrl}${separator}tag=${AMAZON_ASSOCIATE_TAG}`;
  }

  if (item.amazonAsinOrSearch) {
    const query = item.amazonAsinOrSearch.trim();
    if (/^[A-Z0-9]{10}$/i.test(query)) {
      return `https://www.amazon.com/dp/${query}?tag=${AMAZON_ASSOCIATE_TAG}`;
    }
    return `https://www.amazon.com/s?k=${encodeURIComponent(query)}&tag=${AMAZON_ASSOCIATE_TAG}`;
  }

  return `https://www.amazon.com/s?k=${encodeURIComponent(item.name)}&tag=${AMAZON_ASSOCIATE_TAG}`;
}

